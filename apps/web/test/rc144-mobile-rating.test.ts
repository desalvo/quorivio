test('RC144 mobile layout survives backup and conflict-safe three-way merge',()=>{
 const activity={page_design:{widgets,header:'hello',mobile:{backgroundColor:'#ffffff',positions:{title:{x:4,y:4,width:92,height:12}}}}};
 const base=pageDraftFromActivity(activity);
 assert.equal(base.mobile?.backgroundColor,'#ffffff');
 const backup=createPageDraftBackup('session','page',3,base,base);
 const imported=parsePageDraftBackup(JSON.stringify(backup),'session','page');
 assert.deepEqual(imported.draft.mobile,base.mobile);
 const local={...base,mobile:{...base.mobile,backgroundColor:'#ddeeff'}};
 const remote={...base,questionHeader:'new remote title'};
 const merged=mergePageDrafts(base,local,remote);
 assert.equal(merged.conflicts.length,0);
 assert.equal(merged.draft.questionHeader,'new remote title');
 assert.equal(merged.draft.mobile?.backgroundColor,'#ddeeff');
 const conflict=mergePageDrafts(base,local,{...base,mobile:{...base.mobile,backgroundColor:'#abcdef'}});
 assert.equal(conflict.conflicts[0]?.path,'/mobile/backgroundColor');
 const selected=mergePageDrafts(base,local,{...base,mobile:{...base.mobile,backgroundColor:'#abcdef'}},{'/mobile/backgroundColor':'local'});
 assert.equal(selected.draft.mobile?.backgroundColor,'#ddeeff');
});
