#!/usr/bin/env python3
"""RC170 Chromium: footer number matches real, preview and editor phone stages.

No authentication, external network, production URLs or session data are used.
Checks both independent spacing and a manually positioned number; a previous
5px/10px CSS override silently erased these options on the two phone stages.
"""
from __future__ import annotations
import os
from pathlib import Path
import shutil
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[1]
CSS = (ROOT / 'apps/web/src/style.css').read_text(encoding='utf-8')


def number(custom: bool, font: int, right: int, bottom: int) -> str:
    # Equivalent to the props generated by SlideCanvasNumber in main.tsx.
    location = ('--footer-number-x:82%;--footer-number-y:91%;'
                'right:auto;bottom:auto;') if custom else ''
    return (f'<span class="slide-canvas-page-number" '
            f'data-custom-number="{str(custom).lower()}" '
            f'style="font-family:Arial;font-size:{font/12.8:.5f}cqw;'
            f'--footer-pad-right:{right/12.8:.5f}cqw;'
            f'--footer-pad-bottom:{bottom/12.8:.5f}cqw;'
            f'--phone-footer-number-font-size:{font}px;'
            f'--phone-footer-pad-right:{right}px;'
            f'--phone-footer-pad-bottom:{bottom}px;{location}">7</span>')


def html(custom: bool, font: int, right: int, bottom: int) -> str:
    widget = number(custom, font, right, bottom)
    return ('<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1">'
            '</head><body>'
            '<div class="editor-ux-v2"><div class="canvas-editor-group" data-canvas-device="phone">'
            f'<div class="widget-canvas" id="phone-editor" style="position:relative;width:390px;height:940px">{widget}</div>'
            '</div></div>'
            '<div class="rehearsal-phone-stage" style="position:relative;transform:none;width:390px;height:940px">'
            '<div class="rehearsal-slide" style="height:100%">'
            f'<div class="rehearsal-widgets" id="phone-preview">{widget}</div></div></div>'
            '<div class="audience-widget-layout stage-phone" id="phone-live" '
            f'style="position:relative;width:390px;height:940px">{widget}</div>'
            '</body></html>')


def metrics(page):
    return page.evaluate('''() => ['#phone-editor','#phone-preview','#phone-live'].map(id=>{
        const stage=document.querySelector(id),number=stage.querySelector('.slide-canvas-page-number');
        const box=stage.getBoundingClientRect(),rect=number.getBoundingClientRect(),computed=getComputedStyle(number);
        return {id,stageWidth:box.width,font:parseFloat(computed.fontSize),family:computed.fontFamily,
                fromRight:box.right-rect.right,fromBottom:box.bottom-rect.bottom,
                fromLeft:rect.right-box.left,fromTop:rect.bottom-box.top,
                left:computed.left,right:computed.right,top:computed.top,bottom:computed.bottom};
    })''')


def run():
    chromium = os.environ.get('QUORIVIO_CHROMIUM_PATH') or shutil.which('chromium') or shutil.which('google-chrome')
    if not chromium:
        raise RuntimeError('Chromium required for actual RC170 footer-number geometry')
    with sync_playwright() as playwright:
        browser=playwright.chromium.launch(headless=True,executable_path=chromium,args=['--no-sandbox'])
        try:
            for viewport in (390, 1440):
                for custom in (False, True):
                    for font, right, bottom in ((14, 5, 5), (23, 17, 13)):
                        page=browser.new_page(viewport={'width':viewport,'height':900})
                        page.set_content(html(custom,font,right,bottom))
                        page.add_style_tag(content=CSS + "\n#phone-editor{border:0!important;box-shadow:none!important}")
                        values=metrics(page)
                        for actual in values:
                            assert abs(actual['font']-font)<0.3, (viewport,custom,font,values)
                            assert actual['family'].startswith('Arial'), values
                            if custom:
                                assert abs(actual['fromLeft']-390*.82)<1.2, (viewport,custom,values)
                                assert abs(actual['fromTop']-940*.91)<1.2, (viewport,custom,values)
                            else:
                                assert abs(actual['fromRight']-right)<1.2, (viewport,custom,values)
                                assert abs(actual['fromBottom']-bottom)<1.2, (viewport,custom,values)
                        for key in ('font','fromLeft','fromTop') if custom else ('font','fromRight','fromBottom'):
                            assert max(v[key] for v in values)-min(v[key] for v in values)<1.2,(viewport,custom,key,values)
                        print(f'PASS RC170 Chromium {viewport}px: 3 phone surfaces font={font}px custom={custom} insets={right}/{bottom}px')
                        page.close()
        finally:
            browser.close()


if __name__=='__main__':
    run()
